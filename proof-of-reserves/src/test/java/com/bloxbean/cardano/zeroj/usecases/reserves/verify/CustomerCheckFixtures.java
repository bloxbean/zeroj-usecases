/**
 * Generates {@code src/test/resources/customer-check-fixtures.json}: the leaf-encoding vectors, a
 * depth-4 salted tree with one customer's inclusion data, and the customer-check scenarios. The
 * Java check ({@link CustomerCheckTest}) and the browser check
 * ({@code frontend/test/customerCheck.test.mjs}) both run every scenario, so they cannot drift
 * apart. Values are deterministic (salts derived from labels) so the file is reproducible.
 */
final class CustomerCheckFixtures {

    static final String RESOURCE = "src/test/resources/customer-check-fixtures.json";
    static final int DEPTH = 4;
    static final long GENESIS = 1_800_000_000_000L;
    static final long PERIOD_MS = 300_000L;
    static final long PERIOD = 12;
    static final long NOW = GENESIS + PERIOD * PERIOD_MS + 120_000L;
    static final String CUSTOMER = "alice";

    private static final ObjectMapper JSON = new ObjectMapper();

    private CustomerCheckFixtures() {}

    static ObjectNode generate() {
        ObjectNode root = JSON.createObjectNode();
        root.put("description", "ADR-0009 D4 customer-check fixtures: generated by CustomerCheckFixtures.java; "
                + "regenerate with RESERVES_REGENERATE_FIXTURES=true ./gradlew test --tests '*CustomerCheckTest'");
        root.set("vectors", vectors());

        // A depth-4 tree of 8 accounts and 8 padding leaves, built level by level.
        String[] ids = {"alice", "bob", "charlie", "diana", "eve", "frank", "grace", "henry"};
        long[] balances = {500_000_000L, 1_200_000_000L, 300_000_000L, 2_500_000_000L,
                800_000_000L, 150_000_000L, 3_000_000_000L, 50_000_000L};
        int n = 1 << DEPTH;
        BigInteger[] salts = new BigInteger[n];
        BigInteger[][] tree = new BigInteger[DEPTH + 1][];
        tree[0] = new BigInteger[n];
        BigInteger total = BigInteger.ZERO;
        for (int i = 0; i < n; i++) {
            if (i < ids.length) {
                salts[i] = salt("salt/" + ids[i]);
                tree[0][i] = ReserveLeaves.leaf(ReserveLeaves.saltedId(ids[i], salts[i]), BigInteger.valueOf(balances[i]));
                total = total.add(BigInteger.valueOf(balances[i]));
            } else {
                tree[0][i] = ReserveLeaves.leaf(salt("padding/" + i), BigInteger.ZERO);
            }
        }
        for (int level = 1; level <= DEPTH; level++) {
            tree[level] = new BigInteger[tree[level - 1].length / 2];
            for (int i = 0; i < tree[level].length; i++) {
                tree[level][i] = ReserveLeaves.node(tree[level - 1][2 * i], tree[level - 1][2 * i + 1]);
            }
        }
        BigInteger treeRoot = tree[DEPTH][0];
        int leafIndex = 0;
        List<BigInteger> siblings = new ArrayList<>();
        for (int level = 0, i = leafIndex; level < DEPTH; level++, i >>= 1) siblings.add(tree[level][i ^ 1]);

        ObjectNode inclusion = root.putObject("inclusion");
        inclusion.put("accountId", CUSTOMER);
        inclusion.put("salt", salts[leafIndex].toString());
        inclusion.put("balance", Long.toString(balances[leafIndex]));
        inclusion.put("leafIndex", leafIndex);
        ArrayNode sib = inclusion.putArray("siblings");
        siblings.forEach(s -> sib.add(s.toString()));
        root.put("root", treeRoot.toString());

        String policy = HexUtil.encodeHexString(Blake2bUtil.blake2bHash224("reserves/policy".getBytes(StandardCharsets.UTF_8)));
        String otherPolicy = HexUtil.encodeHexString(Blake2bUtil.blake2bHash224("reserves/other".getBytes(StandardCharsets.UTF_8)));
        ObjectNode deployment = root.putObject("deployment");
        deployment.put("policyId", policy);
        deployment.put("genesisMs", GENESIS);
        deployment.put("periodMs", PERIOD_MS);

        String unit = AttestationPeriods.unit(policy, PERIOD);
        String nextUnit = AttestationPeriods.unit(policy, PERIOD + 1);
        String scriptAddr = scriptAddress(policy);
        String otherAddr = scriptAddress(otherPolicy);
        String stakedAddr = AddressProvider.getBaseAddress(Credential.fromScript(HexUtil.decodeHexString(policy)),
                Credential.fromKey(Blake2bUtil.blake2bHash224("stake".getBytes(StandardCharsets.UTF_8))),
                Networks.testnet()).toBech32();
        BigInteger liabilities = total;
        BigInteger reserves = total.add(BigInteger.valueOf(1_000_000_000L));
        String goodDatum = datumHex(PERIOD, treeRoot, liabilities, reserves);
        ObjectNode good = utxo("aa", scriptAddr, unit, 1, goodDatum);
        ObjectNode mint = history("m1", unit, 1);
        ObjectNode mint2 = history("m2", unit, 1);
        ObjectNode burn = history("b1", unit, -1);

        ArrayNode s = root.putArray("scenarios");
        s.add(scenario("verified", null, NOW, 100, utxos(unit, good), pages(unit, List.of(List.of(mint))), "VERIFIED"));
        s.add(scenario("verified, history read across pages", null, NOW, 1, utxos(unit, good),
                pages(unit, List.of(List.of(mint), List.of())), "VERIFIED"));
        s.add(scenario("tampered path", override("sibling1", tweak(siblings.get(1))), NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint))), "ROOT_MISMATCH"));
        s.add(scenario("tampered balance", override("balance", "500000001"), NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint))), "ROOT_MISMATCH"));
        s.add(scenario("wrong salt", override("salt", tweak(salts[leafIndex])), NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint))), "ROOT_MISMATCH"));
        s.add(scenario("wrong leaf index", override("leafIndex", "1"), NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint))), "ROOT_MISMATCH"));
        s.add(scenario("fake attestation: another tree's root", null, NOW, 100,
                utxos(unit, utxo("aa", scriptAddr, unit, 1, datumHex(PERIOD, tweakInt(treeRoot), liabilities, reserves))),
                pages(unit, List.of(List.of(mint))), "ROOT_MISMATCH"));
        s.add(scenario("fake attestation: token at another script's address", null, NOW, 100,
                utxos(unit, utxo("aa", otherAddr, unit, 1, goodDatum)), pages(unit, List.of(List.of(mint))),
                "NOT_AT_SCRIPT_ADDRESS"));
        s.add(scenario("fake attestation: script address with a stake part", null, NOW, 100,
                utxos(unit, utxo("aa", stakedAddr, unit, 1, goodDatum)), pages(unit, List.of(List.of(mint))),
                "NOT_AT_SCRIPT_ADDRESS"));
        s.add(scenario("fake attestation: datum with an extra field", null, NOW, 100,
                utxos(unit, utxo("aa", scriptAddr, unit, 1, extraFieldDatumHex(treeRoot, liabilities, reserves))),
                pages(unit, List.of(List.of(mint))), "BAD_DATUM"));
        s.add(scenario("fake attestation: no inline datum", null, NOW, 100,
                utxos(unit, utxo("aa", scriptAddr, unit, 1, null)), pages(unit, List.of(List.of(mint))), "BAD_DATUM"));
        s.add(scenario("datum for another period", null, NOW, 100,
                utxos(unit, utxo("aa", scriptAddr, unit, 1, datumHex(PERIOD - 1, treeRoot, liabilities, reserves))),
                pages(unit, List.of(List.of(mint))), "WRONG_PERIOD"));
        s.add(scenario("stale period: only the previous period is attested", null, NOW + PERIOD_MS, 100,
                utxos(unit, good), pages(unit, List.of(List.of(mint))), "NO_ATTESTATION"));
        s.add(scenario("before genesis", null, GENESIS - 1, 100, utxos(unit, good), pages(unit, List.of(List.of(mint))),
                "BEFORE_GENESIS"));
        s.add(scenario("duplicate: two separately valid mints, both live", null, NOW, 100,
                utxos(unit, good, utxo("bb", scriptAddr, unit, 1, datumHex(PERIOD, tweakInt(treeRoot), liabilities, reserves))),
                pages(unit, List.of(List.of(mint, mint2))), "DUPLICATE_ATTESTATION"));
        s.add(scenario("duplicate: two mints in the history", null, NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint, mint2))), "DUPLICATE_ATTESTATION"));
        s.add(scenario("duplicate: burn followed by a re-mint", null, NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint, burn, mint2))), "DUPLICATE_ATTESTATION"));
        s.add(scenario("duplicate: second mint on page 2", null, NOW, 1, utxos(unit, good),
                pages(unit, List.of(List.of(mint), List.of(mint2), List.of())), "DUPLICATE_ATTESTATION"));
        s.add(scenario("duplicate: quantity 2 in one output", null, NOW, 100,
                utxos(unit, utxo("aa", scriptAddr, unit, 2, goodDatum)), pages(unit, List.of(List.of(history("m1", unit, 2)))),
                "DUPLICATE_ATTESTATION"));
        s.add(scenario("history unavailable", null, NOW, 100, utxos(unit, good), errorAt(unit, 1, List.of()),
                "HISTORY_INCOMPLETE"));
        s.add(scenario("history unavailable on page 2", null, NOW, 1, utxos(unit, good),
                errorAt(unit, 2, List.of(List.of(mint))), "HISTORY_INCOMPLETE"));
        s.add(scenario("history longer than the page limit", null, NOW, 1, utxos(unit, good),
                repeat(unit, List.of(mint)), "HISTORY_INCOMPLETE"));
        s.add(scenario("history without the mint of a live token", null, NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of())), "HISTORY_INCOMPLETE"));
        s.add(scenario("history entry for another unit", null, NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(history("m1", nextUnit, 1)))), "HISTORY_INCOMPLETE"));
        ObjectNode noTime = scenario("chain time unavailable", null, NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint))), "INDEXER_UNAVAILABLE");
        ((ObjectNode) noTime.get("indexer")).putNull("latestTimeMs");
        s.add(noTime);
        ObjectNode noUtxos = scenario("token outputs unavailable", null, NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint))), "INDEXER_UNAVAILABLE");
        ((ObjectNode) noUtxos.get("indexer")).put("utxosError", true);
        s.add(noUtxos);
        s.add(scenario("leaf index out of range", override("leafIndex", "16"), NOW, 100, utxos(unit, good),
                pages(unit, List.of(List.of(mint))), "BAD_INPUT"));
        return root;
    }

    /** idTag vectors: the empty id, 31 and 32 bytes, leading zero bytes, and non-ASCII UTF-8. */
    private static ObjectNode vectors() {
        ObjectNode v = JSON.createObjectNode();
        v.put("idDomain", ReserveLeaves.ID_DOMAIN);
        v.put("idDomainTag", ReserveLeaves.ID_TAG_DOMAIN.toString());
        ArrayNode tags = v.putArray("idTags");
        for (String id : idVectors()) {
            ObjectNode t = tags.addObject();
            t.put("utf8Hex", HexUtil.encodeHexString(id.getBytes(StandardCharsets.UTF_8)));
            t.put("idTag", ReserveLeaves.idTag(id).toString());
        }
        ObjectNode leaf = v.putObject("leaf");
        BigInteger salt = salt("vector/salt");
        leaf.put("accountId", "alice");
        leaf.put("salt", salt.toString());
        leaf.put("balance", "500000000");
        BigInteger saltedId = ReserveLeaves.saltedId("alice", salt);
        leaf.put("saltedId", saltedId.toString());
        leaf.put("leaf", ReserveLeaves.leaf(saltedId, BigInteger.valueOf(500_000_000L)).toString());
        return v;
    }

    static List<String> idVectors() {
        return List.of("", "a", "alice", "a".repeat(31), "a".repeat(32), "\0\0alice", "\0", "a".repeat(62),
                "a".repeat(63), "büro-€");
    }

    /** A deterministic 252-bit value from a label. */
    static BigInteger salt(String label) {
        return new BigInteger(1, Blake2bUtil.blake2bHash256(label.getBytes(StandardCharsets.UTF_8))).shiftRight(4);
    }

    static String scriptAddress(String policy) {
        return AddressProvider.getEntAddress(Credential.fromScript(HexUtil.decodeHexString(policy)), Networks.testnet()).toBech32();
    }

    static String datumHex(long period, BigInteger root, BigInteger liabilities, BigInteger reserves) {
        return OnChainReserveService.attestationDatum(period, root, liabilities, reserves).serializeToHex();
    }

    private static String extraFieldDatumHex(BigInteger root, BigInteger liabilities, BigInteger reserves) {
        PlutusData d = ConstrPlutusData.builder().alternative(0).data(ListPlutusData.of(
                BigIntPlutusData.of(PERIOD), BigIntPlutusData.of(root), BigIntPlutusData.of(liabilities),
                BigIntPlutusData.of(reserves), BigIntPlutusData.of(1))).build();
        return d.serializeToHex();
    }

    private static String tweak(BigInteger v) {
        return tweakInt(v).toString();
    }

    private static BigInteger tweakInt(BigInteger v) {
        return v.flipBit(0);
    }

    private static ObjectNode override(String field, String value) {
        ObjectNode o = JSON.createObjectNode();
        o.put(field, value);
        return o;
    }

    private static ObjectNode utxo(String tx, String address, String unit, long qty, String datum) {
        ObjectNode u = JSON.createObjectNode();
        u.put("txHash", tx.repeat(32));
        u.put("outputIndex", 0);
        u.put("address", address);
        ObjectNode amounts = u.putObject("amounts");
        amounts.put("lovelace", "3000000");
        amounts.put(unit, Long.toString(qty));
        if (datum == null) u.putNull("inlineDatum");
        else u.put("inlineDatum", datum);
        return u;
    }

    private static ObjectNode history(String tx, String unit, long qty) {
        ObjectNode h = JSON.createObjectNode();
        h.put("txHash", tx.repeat(32));
        h.put("unit", unit);
        h.put("quantity", Long.toString(qty));
        return h;
    }

    private static ObjectNode utxos(String unit, ObjectNode... us) {
        ObjectNode o = JSON.createObjectNode();
        ArrayNode a = o.putArray(unit);
        for (ObjectNode u : us) a.add(u);
        return o;
    }

    private static ObjectNode pages(String unit, List<List<ObjectNode>> pages) {
        ObjectNode o = JSON.createObjectNode();
        ArrayNode ps = o.putObject(unit).putArray("pages");
        for (var page : pages) {
            ArrayNode p = ps.addArray();
            page.forEach(p::add);
        }
        return o;
    }

    private static ObjectNode errorAt(String unit, int page, List<List<ObjectNode>> pages) {
        ObjectNode o = pages(unit, pages);
        ((ObjectNode) o.get(unit)).put("errorAtPage", page);
        return o;
    }

    private static ObjectNode repeat(String unit, List<ObjectNode> page) {
        ObjectNode o = pages(unit, List.of(page));
        ((ObjectNode) o.get(unit)).put("repeat", true);
        return o;
    }

    private static ObjectNode scenario(String name, ObjectNode inclusionOverride, long now, int pageSize,
                                       ObjectNode utxos, ObjectNode history, String expected) {
        ObjectNode s = JSON.createObjectNode();
        s.put("name", name);
        if (inclusionOverride != null) s.set("override", inclusionOverride);
        s.put("pageSize", pageSize);
        ObjectNode indexer = s.putObject("indexer");
        indexer.put("latestTimeMs", now);
        indexer.set("utxos", utxos);
        indexer.set("history", history);
        s.put("expected", expected);
        return s;
    }
}
